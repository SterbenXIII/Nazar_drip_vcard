import type { Translatable } from '../types/seo'

export interface District {
  /** URL-safe slug: kebab-case transliteration */
  slug: string
  /** Display name */
  name: Translatable<string>
  /** Locative case for use in sentences */
  nameLocative: Translatable<string>
  /** Approximate travel time from city center in minutes */
  travelMinutes: number
}

export interface City {
  /** URL-safe slug */
  slug: string
  /** Display name: "Львів" / "Львов" */
  name: Translatable<string>
  /** Locative case: "у Львові" / "во Львове" */
  nameLocative: Translatable<string>
  /** Oblast region display name */
  region: Translatable<string>
  /** Unique local description for the city page (SEO differentiation) */
  localDescription: Translatable<string>
  /** Districts — only for Lviv city; empty array for oblast cities */
  districts: readonly District[]
}

