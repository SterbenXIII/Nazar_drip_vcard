export function getCityBySlug(slug: string): City | undefined {
  if (slug === lvivCity.slug) return lvivCity
  return allCities.find((c) => c.slug === slug)
}

export function getLvivDistrictBySlug(slug: string): District | undefined {
  return lvivCity.districts.find((d) => d.slug === slug)
}
